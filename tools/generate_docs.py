"""Write the reference tables in docs/ from data/: Calibers.md, Armor.md and Creatures.md.

python -I tools/generate_docs.py

The tables are generated so they always match the values the mod runs on; never edit them by hand. Rerun this
after changing any file in data/. The derivations (stop level, head explosion range, limb removal, energy left
after air drag) are the ones generate_terminal_data.py and src/Presets.cpp use.
"""
import json
import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
HEADER = "<!-- Generated by tools/generate_docs.py from data/. Do not edit. -->\n\n"

METRES_PER_FOOT = 0.3048
BC_TO_KG_PER_SQUARE_METRE = 703.07
DRAG_CONSTANT = math.pi / 8.0 * 1.225
SPEED_OF_SOUND = 340.0
STEP_METRES = 5.0
G1 = ((0.0, 0.2629), (0.5, 0.2032), (0.7, 0.2165), (0.8, 0.2546), (0.9, 0.3415), (0.95, 0.4084), (1.0, 0.4805),
      (1.05, 0.5427), (1.1, 0.5883), (1.2, 0.6393), (1.35, 0.6621), (1.5, 0.6573), (1.75, 0.6280), (2.0, 0.5934),
      (2.5, 0.5397), (3.0, 0.5133), (3.5, 0.5040), (4.0, 0.5006))
LIMBS = {1: "head", 2: "eye", 3: "look target", 4: "fly grab", 5: "second head part", 6: "left arm 1", 7: "left arm 2",
         8: "right arm 1", 9: "right arm 2", 10: "left leg 1", 11: "left leg 2", 12: "left leg 3", 13: "right leg 1",
         14: "right leg 2", 15: "right leg 3", 16: "brain", 17: "weapon", 18: "root", 19: "COM", 20: "pelvis",
         21: "camera", 22: "offset root", 23: "left foot", 24: "right foot", 25: "face target"}


def load(name):
    return json.loads((ROOT / "data" / name).read_text(encoding="utf-8"))


def g1(mach):
    for (low_mach, low), (high_mach, high) in zip(G1, G1[1:]):
        if mach <= high_mach:
            return low + (high - low) * (mach - low_mach) / (high_mach - low_mach)
    return G1[-1][1]


def damage_at(damage, fps, bc, metres, exponent):
    """Damage left after flying this far: the runtime's 5 m drag steps, then the damage model's energy exponent."""
    muzzle = fps * METRES_PER_FOOT
    factor = DRAG_CONSTANT / (bc * BC_TO_KG_PER_SQUARE_METRE)
    speed = muzzle
    remaining = metres
    while remaining > 0:
        speed *= math.exp(-factor * g1(speed / SPEED_OF_SOUND) * min(remaining, STEP_METRES))
        remaining -= STEP_METRES
    kept = (speed / muzzle) ** 2
    return damage * kept ** exponent


def whole(value):
    return "<1" if value < 0.5 else f"{value:.0f}"


def number(value):
    return f"{value:,.0f}" if value >= 100 else f"{value:g}"


def write(name, text):
    (DOCS / name).write_text(HEADER + text.rstrip("\n") + "\n", encoding="ascii", newline="\n")
    print(f"wrote docs/{name}")


def calibers():
    model = load("RealisticDamageModel.json")
    levels = load("ArmorLevels.json")
    registry = load("BallisticRegistry.json")
    flight_data = load("CartridgeFlight.json")
    flight = {row["id"]: row for row in flight_data["cartridges"]}
    exponent = model["model"]["energyExponent"]

    stop = {}
    for level, ids in levels["stopLevels"].items():
        for cartridge in ids.split():
            stop[cartridge] = "none" if level == "none" else f"level {level}"

    names = {row["id"]: row["name"] for row in registry["projectiles"] if "name" in row}
    for row in registry["vanillaAmmo"]:
        if not row["notPlayable"]:
            names.setdefault(row["profile"], row["name"])

    burst = levels["headBurst"]
    shotguns = set(burst["shotguns"].split())

    def head_burst(cartridge, energy):
        if energy >= burst["atAnyRangeEnergyFtLb"]:
            return "any range"
        if cartridge in shotguns:
            return f"{burst['shotgunRangeMeters']} m"
        if energy >= burst["atContactEnergyFtLb"]:
            return f"{burst['contactRangeMeters']} m"
        return "never"

    def table(profiles):
        rows = []
        for profile in sorted(profiles, key=lambda row: (row["energyFtLb"], row["id"])):
            cartridge = profile["id"]
            energy = profile["energyFtLb"]
            fly = flight[cartridge]
            rows.append("| {} | `{}` | {} | {:.3f} | {:g} | {} | {} | {} | {} | {} | {:,.0f} | {:.3f} | {} | {} |".format(
                names.get(cartridge, cartridge), cartridge, number(energy), profile["diameterIn"], profile["damage"],
                whole(damage_at(profile["damage"], fly["fps"], fly["bc"], 100, exponent)),
                whole(damage_at(profile["damage"], fly["fps"], fly["bc"], 300, exponent)),
                stop[cartridge], head_burst(cartridge, energy), "yes" if energy >= levels["severEnergyFtLb"] else "no",
                fly["fps"], fly["bc"], profile.get("damageSource", ""), fly["source"]))
        return "\n".join([
            "| Caliber | ID | Energy | Bullet | Damage | At 100 m | At 300 m | Stopped by | Head explodes | Removes limbs | Muzzle velocity | BC | Energy source | Flight source |",
            "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
            *rows,
        ])

    shipped = [row for row in registry["projectiles"] if row.get("shipped", True)]
    mapped = [row for row in registry["projectiles"] if not row.get("shipped", True)]

    sources = model["sources"]
    source_rows = [
        f"| `{key}` | [{entry['url'].split('/wiki/')[-1].replace('_', ' ')}]({entry['url']}) | {entry['description']} |"
        if "url" in entry else f"| `{key}` | Estimate | {entry['description']} |"
        for key, entry in sources.items()
    ]
    rated = levels["ratedEnergyFtLb"]
    write("Calibers.md", f"""# Calibers

Every caliber Flying BRICKS owns, from the weakest round to the heaviest. [Damage model](DamageModel.md) explains how
these numbers are used, and [Ballistics](Ballistics.md) how rounds fly.

- **Energy** is muzzle energy in foot-pounds and **Bullet** the bullet diameter in inches, the two inputs of the
  damage formula.
- **Damage** is what the round does to an unarmored human with 100 health, at the muzzle. A shotgun's damage is the
  whole shot, which the game divides among its pellets.
- **At 100 m** and **At 300 m** are the same hit after air drag has taken part of the round's energy.
- **Stopped by** is the lowest worn armor level that stops the round ({', '.join(f'level {k} is rated for {v} ft-lb' for k, v in rated.items())});
  "none" means no worn armor stops it.
- **Head explodes** is the range within which a killing head hit can burst the head. **Removes limbs** says whether a
  killing limb hit can sever the limb.
- **Muzzle velocity** (feet per second) and **BC** (G1 ballistic coefficient) drive the flight.
- **Energy source** and **Flight source** name where the values come from; the keys are listed under
  [Sources](#sources).

{table(shipped)}

## Mapped, not shipped

Real cartridges with full data that no supported weapon fires. The mod has no ammunition for them, so a patch file
cannot use these IDs: such a row is reported in the log and skipped. A caliber moves to the table above when a weapon
needs it.

{table(mapped)}

## Sources

Energy and bullet diameter:

| Key | Source | What it gives |
| --- | --- | --- |
{chr(10).join(source_rows)}

Flight: {flight_data['sources']}

{model['model']['caveat']}
""")


def armor():
    levels = load("ArmorLevels.json")
    rated = levels["ratedEnergyFtLb"]
    rules = []
    for rule in levels["armorRules"]:
        match = f"starts with `{rule['prefix']}`" if "prefix" in rule else f"contains `{rule['contains']}`"
        rules.append(f"| {match} | {rule['level']} | {rule['heavyLevel']} |")
    weave = [f"| {row['name']} | `{row['editorID']}` | {row['level']} | {row['description']} |" for row in levels["ballisticWeave"]]
    burst = levels["headBurst"]
    write("Armor.md", f"""# Armor

Worn armor has a level from 0 (clothing) to 4, compared with the protection levels of NIJ Standard 0123.00. A round
is stopped by armor at or above its caliber's stop level ([Calibers](Calibers.md)). [Damage model](DamageModel.md)
explains what happens to a round that is stopped and one that gets through.

## Levels

| Level | NIJ rating | Rated energy (ft-lb) |
| --- | --- | --- |
| 1 | HG1 | {rated['1']} |
| 2 | HG2 | {rated['2']} |
| 3 | RF1 | {rated['3']} |
| 4 | RF3 | {rated['4']} |

{levels['ratingSources']}

## Armor rules

Each vanilla and DLC armor piece takes its level from the first rule its editor ID matches: a prefix exactly, a
"contains" rule in the lower-cased ID.
**Heavy** is the level with a heavy armor mod attached (an object mod whose editor ID matches
`{levels['heavyModPattern']}`). Armor no rule matches, including other mods' armor, takes a level from its armor
rating, scaled by the slots it covers: below 5 it is clothing, then levels 1 to 4 from ratings of 5, 15, 25 and 40 in
torso terms. A helmet is never above level 2.

| Editor ID | Level | Heavy |
| --- | --- | --- |
{chr(10).join(rules)}

## Ballistic Weave

The five Ballistic Weave tiers give the clothing they are applied to a fixed level, and the mod renames them to show it.

| Name | Editor ID | Level | Description |
| --- | --- | --- | --- |
{chr(10).join(weave)}

## Heads and limbs

- A killing head hit can burst the head when the round carries at least {burst['atContactEnergyFtLb']} ft-lb within
  {burst['contactRangeMeters']} m, at least {burst['atAnyRangeEnergyFtLb']} ft-lb at any range, or is a heavy shotgun
  round ({', '.join(f'`{s}`' for s in burst['shotguns'].split())}) within {burst['shotgunRangeMeters']} m.
- A killing limb hit can sever the limb when the round carries at least {levels['severEnergyFtLb']} ft-lb.
""")


def creatures():
    data = load("CreatureLevels.json")
    rows = []
    for race in sorted(data["races"], key=lambda row: (row["plugin"], row["name"])):
        zones = "; ".join(
            "{}: {}".format(LIMBS.get(zone["limb"], f"limb {zone['limb']}"), ", ".join(part for part in (
                f"level {zone['level']}" if "level" in zone else "",
                f"x{zone['factor']:g}" if zone.get("factor", 1.0) != 1.0 else "",
                "head" if zone.get("head") else "") if part))
            for zone in race["zones"])
        rows.append(f"| {race['name']} | {race['plugin']} | {race['level']} | {zones} | {'yes' if race.get('headKill') else 'no'} | {'yes' if race.get('vanillaRemoval') else 'no'} |")
    write("Creatures.md", f"""# Creatures

Creatures read their own body as armor, on the same levels and stop table as worn armor ([Armor](Armor.md)).
**Level** is the race's default; **Zones** override it for one body part with its own level, a damage factor (x2 is
double damage) or marking it as a head. **Head kill** means a head hit that is not stopped kills outright.
**Native removal** means the game's own head explosion and limb removal rolls stay for that race.

{data['about']}

| Race | Plugin | Level | Zones | Head kill | Native removal |
| --- | --- | --- | --- | --- | --- |
{chr(10).join(rows)}
""")


DOCS.mkdir(exist_ok=True)
calibers()
armor()
creatures()
